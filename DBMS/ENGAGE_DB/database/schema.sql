CREATE TABLE engage_user (
  user_id VARCHAR2(32) PRIMARY KEY, user_name VARCHAR2(120) NOT NULL, full_name VARCHAR2(160),
  handle VARCHAR2(100) UNIQUE NOT NULL, email VARCHAR2(180) UNIQUE, follower_count NUMBER DEFAULT 0 NOT NULL,
  following_count NUMBER DEFAULT 0 NOT NULL, bio CLOB, city VARCHAR2(120), avatar_color VARCHAR2(32), avatar_url VARCHAR2(500), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE post (
  post_id VARCHAR2(32) PRIMARY KEY, user_id VARCHAR2(32) NOT NULL REFERENCES engage_user(user_id), caption CLOB NOT NULL,
  content_type VARCHAR2(32) DEFAULT 'image' NOT NULL, genre VARCHAR2(64) NOT NULL, post_date DATE DEFAULT SYSDATE NOT NULL,
  language VARCHAR2(64), location VARCHAR2(180), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, visual_seed NUMBER DEFAULT 1, media_url VARCHAR2(1000)
);
CREATE TABLE following (
  follower_user_id VARCHAR2(32) REFERENCES engage_user(user_id), following_user_id VARCHAR2(32) REFERENCES engage_user(user_id), followed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_following PRIMARY KEY(follower_user_id,following_user_id)
);
CREATE TABLE likes (
  post_id VARCHAR2(32) REFERENCES post(post_id), user_id VARCHAR2(32) REFERENCES engage_user(user_id), liked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_likes PRIMARY KEY(post_id,user_id)
);
CREATE TABLE saved (
  post_id VARCHAR2(32) REFERENCES post(post_id), user_id VARCHAR2(32) REFERENCES engage_user(user_id), saved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_saved PRIMARY KEY(post_id,user_id)
);
CREATE TABLE reposts (
  repost_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id VARCHAR2(32) REFERENCES post(post_id), user_id VARCHAR2(32) REFERENCES engage_user(user_id), text_highlight CLOB, reposted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_repost UNIQUE(post_id,user_id)
);
CREATE TABLE hashtag (hashtag_id VARCHAR2(32) PRIMARY KEY, hashtag_name VARCHAR2(120) UNIQUE NOT NULL, purpose VARCHAR2(120));
CREATE TABLE post_hashtag (
  post_id VARCHAR2(32) REFERENCES post(post_id), hashtag_id VARCHAR2(32) REFERENCES hashtag(hashtag_id),
  CONSTRAINT pk_post_hashtag PRIMARY KEY(post_id,hashtag_id)
);
CREATE TABLE comments (
  comment_id VARCHAR2(32) PRIMARY KEY, comment_text CLOB NOT NULL, sentiment VARCHAR2(24) DEFAULT 'Neutral' NOT NULL,
  user_id VARCHAR2(32) REFERENCES engage_user(user_id), post_id VARCHAR2(32) REFERENCES post(post_id), towhom VARCHAR2(32),
  numberofreplies NUMBER DEFAULT 0 NOT NULL, positive_replies NUMBER DEFAULT 0 NOT NULL, negative_replies NUMBER DEFAULT 0 NOT NULL,
  parent_comment_id VARCHAR2(32) REFERENCES comments(comment_id), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE comment_likes (
  user_id VARCHAR2(32) REFERENCES engage_user(user_id), comment_id VARCHAR2(32) REFERENCES comments(comment_id), liked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_comment_likes PRIMARY KEY(user_id,comment_id)
);
CREATE TABLE comment_hashtag (
  comment_id VARCHAR2(32) REFERENCES comments(comment_id), hashtag_id VARCHAR2(32) REFERENCES hashtag(hashtag_id),
  CONSTRAINT pk_comment_hashtag PRIMARY KEY(comment_id,hashtag_id)
);
CREATE TABLE reach (
  reach_id VARCHAR2(32) PRIMARY KEY, post_id VARCHAR2(32) UNIQUE REFERENCES post(post_id), impressions NUMBER DEFAULT 0 NOT NULL, unique_reach NUMBER DEFAULT 0 NOT NULL
);
CREATE TABLE student_profile (
  user_id VARCHAR2(32) PRIMARY KEY REFERENCES engage_user(user_id), academic_stage VARCHAR2(64), exam_goal VARCHAR2(64) DEFAULT 'JEE' NOT NULL,
  max_monthly_budget NUMBER(10,2) DEFAULT 0 NOT NULL, budget_preference VARCHAR2(24) DEFAULT 'balanced' NOT NULL,
  preferred_mode VARCHAR2(24) DEFAULT 'online' NOT NULL, language_preference VARCHAR2(64), city VARCHAR2(120), updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE post_learning_signal (
  post_id VARCHAR2(32) PRIMARY KEY REFERENCES post(post_id), exam_goal VARCHAR2(64) DEFAULT 'GENERAL' NOT NULL, topic VARCHAR2(64) NOT NULL, signal_type VARCHAR2(64) NOT NULL
);
CREATE TABLE learning_resource (
  resource_id VARCHAR2(32) PRIMARY KEY, provider_name VARCHAR2(160) NOT NULL, title VARCHAR2(220) NOT NULL, exam_goal VARCHAR2(64) NOT NULL,
  topic VARCHAR2(64) NOT NULL, resource_type VARCHAR2(64) NOT NULL, delivery_mode VARCHAR2(24) NOT NULL, monthly_cost NUMBER(10,2) DEFAULT 0 NOT NULL,
  quality_score NUMBER(4,2) DEFAULT 0 NOT NULL, scholarship_available NUMBER(1) DEFAULT 0 NOT NULL, verified NUMBER(1) DEFAULT 1 NOT NULL, description CLOB, resource_url VARCHAR2(1000), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
